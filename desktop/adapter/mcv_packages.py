"""CV packages for ModularCV Desktop: create, list, review, status and exact-PDF reading.

Thin layer over `modularcv.package`. The verdict (`READY_TO_SEND`, `NEEDS_REVIEW`, `BLOCKED`) and its
reasons always come from a fresh call to the engine (`package.status` / `package.review_summary`): nothing
here computes, caches or stores a verdict. No approval is written here: an approval is a human act that the
engine only accepts from an interactive terminal (`package approve`), and this adapter does not imitate one.

Approval (`package_approve`) is the one writer of a review. It never decides anything: the decision, the reviewer and a
typed hash prefix come from the person at the screen; the adapter re-reads the disk, compares it with the review context the
person was shown, and only then calls the engine's own `package.record_review()` (which re-checks that the package is
reviewable, copies every field from the verified package and refuses to overwrite). It does not simulate a terminal and does
not touch `package approve`. The verdict returned afterwards is a fresh `package.status()`.

Packages are created with the engine's integrated compilation only (`compile_timeout`); a PDF supplied from
elsewhere is never packaged from here, so its provenance can never be presented as verified.

PDF reading is limited to two fixed locations of the active workspace: a package's own
`applications/<name>/cv/resume.pdf` and `out/<name>.pdf`. The bytes are checked with the engine's PDF reader
before they are handed over, together with their SHA-256.
"""
import base64
import json
import os
from pathlib import Path

from mcv_core import Refusal, ensure_dir, locate, problems, workspace_lock
from mcv_jobs import BASE_NAME, OUT_DIR, PLANS_DIR, _stage, offer_path, workspace_file
from modularcv import assemble, canonical, chain, facts, package, paths, pdf, provenance

LIST_LIMIT = 100
CV_FILES = {"pdf": "resume.pdf"}
DEFAULT_COMPILE_TIMEOUT = 120


def _name(value):
    if not isinstance(value, str) or not facts.valid_id(value):
        raise Refusal("PACKAGE_NAME_INVALID", "the package name must be lowercase letters, digits, `.` and `-`")
    return value


def _engine_refusal(error):
    """Turn an engine failure into a Refusal with a stable code. Never carries document text."""
    if isinstance(error, package.PackageError):
        reasons = error.details.get("reasons") if isinstance(error.details, dict) else None
        details = [{"code": r, "message": r, "path": None} for r in reasons or [] if isinstance(r, str)]
        return Refusal(error.code, str(error), details)
    if isinstance(error, chain.ChainError):
        try:
            _stage(error.stage, error.errors)
        except Refusal as refusal:
            return refusal
    if isinstance(error, assemble.AssemblyError):
        return Refusal("ASSEMBLY_REFUSED", "the engine refuses to assemble this plan against the current sources",
                       problems(error.errors))
    if isinstance(error, provenance.SourceProvenanceError):
        return Refusal("PROVENANCE_REFUSED", str(error)[:300],
                       [{"code": error.status, "message": error.reason or str(error)[:200], "path": error.path}])
    if isinstance(error, pdf.PdfError):
        unavailable = error.code == "PDF_UNAVAILABLE"
        return Refusal("PDF_UNAVAILABLE" if unavailable else "PDF_FAILED", error.errors[0].message if error.errors else error.code,
                       problems(error.errors))
    return Refusal("PACKAGE_FAILED", "the engine refused the operation")


ENGINE_FAILURES = (package.PackageError, chain.ChainError, assemble.AssemblyError, provenance.SourceProvenanceError, pdf.PdfError)


def _lexists_link(root, relative):
    """True when any component of `relative` (below `root`) is a symbolic link or a junction."""
    current = Path(root)
    for part in Path(relative).parts:
        current = current / part
        if os.path.islink(str(current)) or (hasattr(current, "is_junction") and current.is_junction()):
            return True
    return False


# --------------------------------------------------------------------------- create

def op_package_create(request):
    root = request.get("root")
    cfg, _ = locate(root, ())
    name = _name(request.get("name"))
    inputs_offer = request.get("offer_file")
    plan_path = workspace_file(root, request.get("plan_file"), PLANS_DIR)
    tex_path = workspace_file(root, request.get("tex_file"), OUT_DIR)
    if tex_path.suffix != ".tex":
        raise Refusal("PATH_UNSAFE", "the document source must be a .tex file generated by this application")
    offer_file = offer_path(root, cfg, inputs_offer)
    if not offer_file.is_file():
        raise Refusal("FILE_UNREADABLE", "the offer does not exist")
    try:
        plan_bytes, tex_bytes = plan_path.read_bytes(), tex_path.read_bytes()
    except OSError as error:
        raise Refusal("FILE_UNREADABLE", "cannot read the plan or the .tex: %s" % error.strerror)
    timeout = request.get("timeout", DEFAULT_COMPILE_TIMEOUT)
    timeout = timeout if isinstance(timeout, int) and not isinstance(timeout, bool) and 5 <= timeout <= 170 else DEFAULT_COMPILE_TIMEOUT
    ensure_dir(root, cfg["packages_dir"])
    with workspace_lock(root):
        try:
            summary = package.create(Path(root), name, str(offer_file), plan_bytes, tex_bytes, None, compile_timeout=timeout)
        except ENGINE_FAILURES as error:
            raise _engine_refusal(error)
    # Creating a package is never an approval: the engine's own summary is passed on with that statement.
    return {"ok": True, "ready_to_send": False, "package": summary, "next": "REVIEW_THEN_APPROVE_IN_A_TERMINAL"}


# --------------------------------------------------------------------------- list / review / status

def review_context(summary):
    """Fingerprint of everything a person is shown before deciding. The same function runs when the review is opened and
    when the decision is submitted: any difference means what was shown is no longer what is on disk."""
    doc = summary["document"]
    return canonical.fingerprint({
        "package": summary["package"], "tailored_cv_id": summary["tailored_cv_id"],
        "document": {"sha256": doc["sha256"], "bytes": doc["bytes"], "pages": doc["pages"], "origin": doc["origin"],
                     "page_verdict": doc["page_verdict"]},
        "reviewed": summary["reviewed"], "to_acknowledge": summary["to_acknowledge"],
        "reasons": sorted(summary["state_now"]["reasons"]), "approval_file": summary["approval_file"],
    })


def _package_names(root, cfg):
    folder = Path(root) / cfg["packages_dir"]
    if not folder.is_dir() or _lexists_link(root, cfg["packages_dir"]):
        return []
    names = []
    for entry in sorted(folder.iterdir()):
        if entry.is_dir() and not os.path.islink(str(entry)) and facts.valid_id(entry.name) and (entry / "package.json").is_file():
            names.append(entry.name)
    return names


def _entry(root, name):
    """One history row: facts from the engine's review summary, the verdict from a fresh `package.status`."""
    row = {"name": name, "readable": True}
    try:
        summary = package.review_summary(Path(root), name)
    except package.PackageError as error:
        row.update(readable=False, code=error.code)
        try:
            verdict = package.status(Path(root), name)
            row["state"] = {"status": verdict["status"], "reasons": verdict["reasons"]}
        except Exception:  # noqa: BLE001 - one broken package must not hide the others
            row["state"] = None
        return row
    except Exception:  # noqa: BLE001
        row.update(readable=False, code="PACKAGE_UNREADABLE", state=None)
        return row
    row.update(job_key=summary["job_key"], language=summary["language"], family=summary["family"],
               document={"available": summary["document"]["sha256"] is not None, "sha256": summary["document"]["sha256"],
                         "pages": summary["document"]["pages"], "origin": summary["document"]["origin"]},
               state=summary["state_now"])
    return row


def op_packages_list(request):
    root = request.get("root")
    cfg, _ = locate(root, ())
    names = _package_names(root, cfg)
    return {"ok": True, "total": len(names), "truncated": len(names) > LIST_LIMIT,
            "packages": [_entry(root, n) for n in names[:LIST_LIMIT]]}


def op_package_review(request):
    """Everything a person needs to examine the exact PDF. Read-only; recomputes the verdict at each call."""
    root = request.get("root")
    locate(root, ())
    name = _name(request.get("name"))
    try:
        summary = package.review_summary(Path(root), name)
        verdict = package.status(Path(root), name)
    except ENGINE_FAILURES as error:
        raise _engine_refusal(error)
    return {"ok": True, "summary": summary, "context": review_context(summary),
            "status": {"status": verdict["status"], "reasons": verdict["reasons"], "warnings": verdict["warnings"],
                       "details": verdict["details"]},
            "approval": {"graphical": True, "cli_available": True}}


def op_package_status(request):
    root = request.get("root")
    locate(root, ())
    name = _name(request.get("name"))
    try:
        verdict = package.status(Path(root), name)
    except ENGINE_FAILURES as error:
        raise _engine_refusal(error)
    return {"ok": True, "status": {"status": verdict["status"], "reasons": verdict["reasons"], "warnings": verdict["warnings"],
                                   "details": verdict["details"]}}


# --------------------------------------------------------------------------- approval (a person's decision)

DECISIONS = ("APPROVED", "REJECTED")
NOTE = "Recorded through the ModularCV Desktop review screen."
NOTE_LIMIT = 500


def _stale(code_message="what is on disk is no longer what was shown: reopen the review"):
    return Refusal("REVIEW_CONTEXT_CHANGED", code_message)


def _is_ours(written, decision, reviewer, note):
    return (isinstance(written, dict) and written.get("decision") == decision and written.get("reviewer") == reviewer
            and written.get("note") == note)


def _withdraw_if_ours(target, raw, written, decision, reviewer, note):
    """Remove the review file only when it is, byte for byte as just read, the one this call wrote. A file that another
    process has replaced in the meantime, or one that cannot be read, is never deleted. Returns True when a file was kept.

    Residual: between the final comparison and the unlink there is an instant a different process could still use; it is
    narrower than the first window and the verdict is recomputed by the engine anyway."""
    if raw is None or not _is_ours(written, decision, reviewer, note):
        return True
    try:
        if target.read_bytes() != raw:
            return True
        target.unlink()
        return False
    except OSError:
        return True


def op_package_approve(request):
    root = request.get("root")
    locate(root, ())
    name = _name(request.get("name"))
    decision = request.get("decision")
    if decision not in DECISIONS:
        raise Refusal("DECISION_INVALID", "the decision must be explicitly APPROVED or REJECTED")
    reviewer = request.get("reviewer")
    if not isinstance(reviewer, str) or not reviewer.strip() or len(reviewer) > 120 or any(ord(c) < 32 for c in reviewer):
        raise Refusal("REVIEWER_REQUIRED", "the reviewer must be named (a short plain name)")
    if request.get("confirm_examined") is not True or request.get("confirm_final") is not True:
        raise Refusal("CONFIRMATION_REQUIRED", "the person must explicitly confirm having examined the document and the final decision")
    for field in ("context", "viewed_sha256", "typed_prefix"):
        if not isinstance(request.get(field), str) or not request[field]:
            raise Refusal("CONFIRMATION_REQUIRED", "the review context, the viewed document hash and the typed prefix are required")
    user_note = request.get("note")
    if user_note is not None and (not isinstance(user_note, str) or len(user_note) > NOTE_LIMIT):
        raise Refusal("VALIDATION_FAILED", "the note must be text of at most %d characters" % NOTE_LIMIT)
    note = NOTE + (" " + " ".join(user_note.split()) if user_note and user_note.strip() else "")

    with workspace_lock(root):
        # 1. Re-read the disk: the engine's own review summary and verdict, now.
        try:
            summary = package.review_summary(Path(root), name)
        except ENGINE_FAILURES as error:
            raise _engine_refusal(error)
        document = summary["document"]
        if document["sha256"] is None:
            raise Refusal("FINAL_DOCUMENT_MISSING", "the package holds no PDF: there is nothing to approve")
        blocking = [r for r in summary["state_now"]["reasons"] if r != "HUMAN_REVIEW_REQUIRED"]
        if blocking:
            raise Refusal("PACKAGE_NOT_REVIEWABLE", "the package has an unresolved problem; a review does not replace a check",
                          [{"code": r, "message": r, "path": None} for r in blocking])  # noqa
        # 2. What the person was shown must still be what is on disk.
        if request["context"] != review_context(summary):
            raise _stale()
        if request["viewed_sha256"] != document["sha256"]:
            raise Refusal("PDF_CHANGED_SINCE_VIEW", "the document on disk is not the one that was displayed: reopen the review")
        # 3. The hash prefix is typed by the person against the displayed fingerprint.
        if request["typed_prefix"].strip().lower() != document["sha256"][:12]:
            raise Refusal("CONFIRMATION_MISMATCH", "the characters typed are not the start of the PDF's SHA-256")
        # 4. The engine writes the review (checks again, copies fields from the verified package, never overwrites).
        try:
            package.record_review(Path(root), name, decision, reviewer.strip(), note)
        except ENGINE_FAILURES as error:
            raise _engine_refusal(error)
        # 5. Guard against a change between step 2 and the engine's own read: the file just written must describe exactly
        #    what was compared. Otherwise withdraw our own just-created file and report it; never leave an approval of
        #    something the person did not see.
        target = paths.resolve_inside(root, summary["approval_file"])
        try:
            raw = target.read_bytes()
            written = json.loads(raw.decode("utf-8"))
            consistent = (written.get("document_sha256") == document["sha256"] and written.get("decision") == decision
                          and written.get("tailored_cv_id") == summary["tailored_cv_id"]
                          and written.get("reviewed") == summary["reviewed"]
                          and written.get("acknowledged") == summary["to_acknowledge"])
        except (OSError, ValueError, AttributeError):
            raw, written, consistent = None, None, False
        if not consistent:
            kept = _withdraw_if_ours(target, raw, written, decision, reviewer.strip(), note)
            raise _stale("the evidence changed while the decision was being recorded: " +
                         ("nothing was kept, reopen the review" if not kept else
                          "a review file that is not the one this screen just wrote was left untouched; check the package status"))
        verdict = package.status(Path(root), name)
    return {"ok": True, "decision": decision, "recorded": True, "approval_file": summary["approval_file"],
            "document_sha256": document["sha256"],
            "status": {"status": verdict["status"], "reasons": verdict["reasons"], "warnings": verdict["warnings"],
                       "details": verdict["details"]}}


# --------------------------------------------------------------------------- exact PDF bytes

def _pdf_location(root, cfg, request):
    package_name, output = request.get("package"), request.get("output")
    if (package_name is None) == (output is None):
        raise Refusal("BAD_REQUEST", "give either a package or a generated output")
    if package_name is not None:
        name = _name(package_name)
        relative = "%s/%s/cv/%s" % (cfg["applications_dir"].rstrip("/"), name, CV_FILES["pdf"])
    else:
        if not isinstance(output, str) or not BASE_NAME.match(output) or output.lower().endswith(".pdf"):
            raise Refusal("PATH_UNSAFE", "the output name is not valid")
        relative = "%s/%s.pdf" % (OUT_DIR, output)
    if _lexists_link(root, relative):
        raise Refusal("PATH_UNSAFE", "the document path may not pass through a symbolic link")
    target = paths.resolve_inside(root, relative)
    if target is None:
        raise Refusal("PATH_UNSAFE", "the document path leaves the workspace")
    return relative, target


def op_pdf_read(request):
    """The exact bytes of a workspace PDF (package or generated output), checked, with SHA-256 and page count.

    `with_bytes: false` returns the same checks without the content (used before opening the system reader)."""
    root = request.get("root")
    cfg, _ = locate(root, ())
    relative, target = _pdf_location(root, cfg, request)
    if not target.is_file():
        raise Refusal("PDF_MISSING", "this document does not exist in the workspace")
    try:
        size = target.stat().st_size
        if size > package.PDF_LIMIT:
            raise Refusal("PDF_TOO_LARGE", "the document exceeds the size limit")
        data = target.read_bytes()
    except OSError as error:
        raise Refusal("FILE_UNREADABLE", "cannot read the document: %s" % error.strerror)
    if not pdf.looks_like_pdf(data):
        raise Refusal("PDF_MALFORMED", "the file is not a complete PDF document")
    pages = pdf.count_pages(data)
    if pages is None:
        raise Refusal("PDF_NO_PAGE", "no page can be read from this PDF")
    out = {"ok": True, "file": relative, "bytes": len(data), "pages": pages, "sha256": canonical.sha256_bytes(data)}
    if request.get("with_bytes", True) is not False:
        out["base64"] = base64.b64encode(data).decode("ascii")
    return out


OPERATIONS = {
    "package_create": op_package_create,
    "packages_list": op_packages_list,
    "package_review": op_package_review,
    "package_status": op_package_status,
    "package_approve": op_package_approve,
    "pdf_read": op_pdf_read,
}
